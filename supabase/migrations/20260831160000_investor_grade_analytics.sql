create or replace function public.log_source_candidate_price()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.price is not null and (tg_op = 'INSERT' or old.price is distinct from new.price) then
    insert into public.offer_price_history(source, source_offer_id, price, area, price_m2, url, seen_at)
    values (new.source, new.source_offer_id, new.price, new.area, new.price_m2, new.url, coalesce(new.last_seen_at, now()))
    on conflict (source, source_offer_id, price) do nothing;
  end if;
  return new;
end;
$$;

revoke all on function public.log_source_candidate_price() from public, anon, authenticated;
grant execute on function public.log_source_candidate_price() to service_role;
drop trigger if exists source_candidate_price_history on public.source_candidates;
create trigger source_candidate_price_history
after insert or update of price on public.source_candidates
for each row execute function public.log_source_candidate_price();

